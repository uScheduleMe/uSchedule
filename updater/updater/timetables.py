def get_parser(**kwargs) -> argparse.ArgumentParser:
    """Create the argument parser used when this script is called.
    """
    parser = argparse.ArgumentParser(
        description="Update timetables.",
        **kwargs,
    )
    parser.add_argument("-y", "--year",
        action="store",
        metavar="YEAR",
        type=int,
        required=True,
        help="specify which year to query",
    )
    parser.add_argument("-t", "--term",
        action="store",
        metavar="TERM",
        choices=["winter", "summer", "fall"],
        required=True,
        help="specify which term to query (winter, summer, fall)",
    )
    parser.add_argument("-s", "--saveraw",
        action="store",
        metavar="/PATH/TO/DIR/",
        default=None,
        required=False,
        help="if given, save raw html in this folder",
    )
    parser.add_argument("subjects",
        action="store",
        nargs="*",
        help="subjects to update",
    )
    parser = logda.configure_parser(parser)
    parser = TimetableConfig.configure_parser(parser)
    return parser

def main(args=None, kwargs={}):
    """The main body of this script when called.

    Args:
        args: Script arguments to be parsed.  If `None`, then
            the command line arguments are parsed.
        kwargs: Arguments passed to `get_parser` which generates
            the `argparse.ArgumentParser`.
    """
    args = get_parser(**kwargs).parse_args(args)
    logda.configure_logging(args)
    TimetableUpdater(
        saveraw=args.saveraw,
        config=TimetableConfig.from_args(args),
    ).update_timetables(
        year=args.year,
        term=args.term,
        search_list=args.subjects,
    )


