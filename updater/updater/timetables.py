def normalize_course(
    course: dict,
    year: int,
    term: str
) -> dict:
    """Converts the timetable format of the scraper to that stored in the DA.

    Args:
        course: The course timetable as returned by the scraper.
        year: The year to which the timetable belongs.
        term: The term to which the timetable belongs.
    """
    output = {
        "sections": {},
        "school": 'uottawa',
        "term": term,
        "year": year,
        "course_code": course["course_code"],
        "subject_code": course["subject_code"],
        "course_name": course["course_name"],
    }
    year_terms = set()
    output["sections"] = dict(
        normalize_section(x, year_terms)
        for x in course["sections"]
    )
    if len(year_terms) != 1:
        logging.warning("Number of (year, term) pairs in sections of"
            + "{} {}, {}{} is {} != 1".format(
                term, year, output["subject_code"],
                output["course_code"], len(year_terms),
        ))
    elif year_terms != {(year, term)}:
        logging.warning("Year and from sections of {} {}, {}{}"
            + "do not match sections: {} {}".format(
                term, year, output["subject_code"],
                output["course_code"], *list(year_terms)[::-1]
        ))
    return output

def groupby(
    seq: Iterable[S],
    func: Callable[[S], T],
    postprocess: Callable[[S], U] = (lambda x:x)
) -> Dict[T, List[U]]:
    """Produce the equivalence classes of `seq` under `func`.

    If `postprocess` is given,
    it is applied to elements as they are added
    to their respective equivalence classes.

    Args:
        seq: Items to be grouped.
        func: The function indicating which items from `seq`
            are to be grouped together.
        postprocess: Function to be applied to the elements
            of `seq` when before they are placed in their groups.

    Returns:
        A `dict` mapping an image of elements of `seq` under `func`
            to a `list` of the elements of `seq` which map to that image.
            If `postprocess` is provided, the it is applied to
            the elements of `seq` before they are placed in the `list`.
    """
    equiv_classes = dict()
    for elt in seq:
        image = func(elt)
        if image not in equiv_classes:
            equiv_classes[image] = []
        equiv_classes[image].append(postprocess(elt))
    return equiv_classes

def normalize_section(
    section: dict,
    year_terms: Tuple[int, str],
) -> Tuple[str, dict]:
    """Normalizes the section data format.

    This function also pulls descriptions and instructors from
    the component-level to the section-level.

    Args:
        section: The `dict` containing the section information
            from the scraper.
        year_terms: Set to propogate up (year, term) tuples
            from the sections.

    Returns:
        A tuple of the section ID, and the reformated section.
    """
    sid = section["label"]
    year_terms.add((section["year"], section["term"]))
    components = section["components"]
    # Normalizing components
    type_count = dict()
    staff = set()
    profs = set()
    descs = set()
    components = [
        normalize_component(x, type_count, staff, profs, descs)
        for x in sorted(components, key=lambda comp:[
            comp[y] for y in ["label", "start_date", "day", "start_time"]
        ])
    ]
    components = {
        k: groupby(v, lambda x:x[0], lambda x:x[1])
        for k, v in groupby(components, lambda x:x[0], lambda x:x[1:]).items()
    }
    # Computing section properties derived from components
    # and returning with id
    profs = ", ".join(profs - {""})
    for ctype, cid, count in staff:
        components[ctype][cid][count]["instructor"] = profs
    return sid, {
        "id": sid,
        "label": sid,
        "instructor": profs,
        "description": ", ".join(descs - {""}),
        "components": components,
    }

def normalize_component(
    component: dict,
    type_count: Dict[Tuple[str, str], int],
    staff: Set[Tuple[str, str, int]],
    profs: Set[str],
    descs: Set[str],
) -> Tuple[str, str, dict]:
    """Normalizes the component data format.

    This function counts each type of component
    and propogates it up to the section-level for grouping.

    It also propogates the descriptions and instructors to
    the section-level.

    Args:
        components: The  `dict` containing the component
            information from the scraper.
        type_count: The `dict` mapping (component-type, component-id)
            tuples to the number of time-slots belonging to
            that component.
        staff: A `set` of the component time-slots (of lectures)
            which are missing instructors.
        profs: A `set` of the instructors (of lectures) of this section.
        descs: A `set` of the descriptions of components in this section.

    Returns:
        A tuple of the component type, ID, and the reformatter component.
    """
    # Transforming the data in each component to desired
    component = {k:v for k, v in component.items() if k != "section_id"}
    if "session_type" in component:
        component["session_type"] = component["session_type"].strip().strip(".").strip()
    prof = component.get("instructor", "").strip()
    component["instructor"] = "" if prof.lower() == "staff" else prof
    # Generating unique id (within a section)
    cid = component["label"]
    if "-" in cid:
        cid = cid.split("-")[0]
    ctype = component["type"]
    count = type_count.get((ctype, cid), 0)
    type_count[(ctype, cid)] = count + 1
    component["id"] = "-".join((cid, ctype, str(count)))
    # Collecting data for future use
    if ctype == "LEC":
        # Prof already normalized
        prof = component["instructor"]
        if prof == "":
            staff.add((ctype, cid, count))
        else:
            profs.add(prof)
    descs.add(component["description"].strip())
    # Returning type, id, and component
    return ctype, cid, component


