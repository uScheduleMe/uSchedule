class TimetableUpdater:
    """This class handles updating the timetables in the DA.
    
    Initializing an instance of this class merely sets
    global parameters and state; in order to actually
    update the DA, the `TimetableUpdater.update_timetables`
    method needs to be called.
    
    The data which is fed to the DA is generated by
    the `uoapi` scraper.
    """
    def __init__(self,
        retries: int = 2,
        notes: Optional["TimetableNotifier"] = None,
        saveraw: Optional[AnyStr] = None,
        config: TimetableConfig = DEFAULT_TT_CONFIG,
    ):
        """
        Throughout the life of this object, `self.notes` is used
        to store messages which should be sent to the maintainers
        of this project (as determined by the `notifier`).

        Args:
            retries:
            notes: A `TimetableNotifier` object; if `None`,
                a new `TimetableNotifier` object is instantiated.
            saveraw: A path to the folder in which the scraper
                should save the raw html from the scrape;
                if `None`, the raw html is not saved.
            config: A `TimetableConfig` object, providing access to all the
                endpoints that will need to be accessed by this updater.
        """
        if not isinstance(retries, int) or retries <= 0:
            retries = float("inf")
        self.retries = retries
        if notes is None:
            notes = TimetableNotifier()
        self.notes = notes
        self.saveraw = saveraw
        self.config = config

    #@TODO Once a subjects table is made in the DA,
    # get subjects from there,
    # and update subjects elsewhere.
    def scrape_subjects(self) -> Generator[List[Dict[str, str]], None, None]:
        """Scrape a list of all subjects.

        Yields:
            A `list` of subjects scraped by `uoapi`.
        """
        for output in self.notes.iter_wrap(
            uoapi.course.py_cli(),
            "Getting subjects: ",
            "CRITICAL",
        ):
            if "subjects" in output:
                yield output["subjects"]

    def get_subject_codes(self,
        subjects: List[Dict[str, str]]
    ) -> Set[str]:
        """Extract subject codes from subject information.

        Given a sequence of subjects
            as output by the scraper,
            returns set of subject codes.

        Args:
            subjects: A `list` of subjects as output by the scraper.

        Returns:
            A `set` of all the subject codes from `subjects`.
        """
        try:
            return {x["subject_code"]
                for x in subjects
                if "subject_code" in x
            }
        except Exception as e:
            logging.debug("Failed to get subject codes", exc_info=True)
            return set()

    def get_subjects(self) -> List[str]:
        """Get all valid subject codes.

        Returns:
            The sorted `list` of all subject codes.
        """
        for output in self.scrape_subjects():
            subjects = self.get_subject_codes(output)
            if len(subjects) > 0:
                logging.info("Got subjects: {}".format(", ".join(subjects)))
                return sorted(subjects)
            logging.warning("No subjects found")
        logging.error("Failed to get subjects")
        self.notes.maintainer("Could not get subjects from scraper")
        return None

    def searches_to_retry(self, messages: List[Dict[str, str]]) -> List[str]:
        """Examines the scraper messages to determine which
        searches should be retried.

        Returns:
            A `list` of the search terms which need to be retried.
        """
        retry = set()
        for msg in messages:
            msg = msg["message"]
            match = re.search("([A-Z]{3,4})_([1-5])(?![0-9])", msg)
            # Split searches which exceeded
            # the maximum number of results
            if ("exceeded maximum" in msg.lower()
                and match is not None
            ):
                s, n = match.groups()
                num = "300" if n != "5" else "500"
                num = s + "{}" + n + num
                searches = {num.format("<"), num.format(">")}
                logging.warning("Added searches: " + " ".join(searches))
                retry |= searches
        return list(retry)

    def handle_scraper_messages(self, messages: Iterable[Dict[str, str]]):
        """Notify maintainers of scraper errors.
        """
        for msg in messages:
            if msg["type"] == "error":
                self.notes.maintainer("[SCRAPER ERROR] "
                    + msg["message"]
                )

    def scrape_timetables(self,
        year: int,
        term: str,
        search_list: Optional[Sequence] = None,
    ) -> Generator[dict, None, None]:
        """Generates scraped course timetables.

        Calls the scraper on the `year` and `term` specified
        to find timetables for the courses/subjects in `search_list`.
        If `search_list` is empty or `None`, scrape all subjects.

        Note that the `self.retries` parameter is used here
        to determine how many times failing search terms should be
        retried.

        Args:
            year: The year to which the timetables should belong.
            term: The term to which timetables should belong.
            search_list: Courses and/or subjects to search for.
                For a complete list of terms which may be searched,
                consult the `uoapi` documentation.

        Yields:
            The timetable of each course which was found in the scrape.
        """
        #@TODO Factor; see line 336 (`update_timetables`)
        # See [CS-59]
        if search_list is None or len(search_list) == 0:
            search_list = self.get_subjects()
        tries_left = self.retries
        searched = set()
        while len(search_list) > 0 and tries_left > 0:
            searched |= set(search_list)
            retry = []
            for output in self.notes.iter_wrap(
                uoapi.timetable.py_cli(search_list, year, term, self.saveraw),
                "Getting timetables: ",
                "ERROR",
            ):
                for course in output.get("timetables", []):
                    yield course
                if len(output.get("messages", [])) > 0:
                    retry += self.searches_to_retry(output["messages"])
                    self.handle_scraper_messages(output["messages"])
            search_list = retry
            tries_left -= 1
        self.notes.maintainer("Scraped {} {} for: {}".format(
            term.capitalize(), year, ", ".join(sorted(searched))
        ))
        if len(search_list) > 0:
            leftover = "Leftover searches: " + " ".join(search_list)
            self.notes.maintainer(leftover)
            logging.warning(leftover)

    def send_timetable_to_da(self,
        course: dict,
        year: int,
        term: str,
    ) -> requests.models.Response:
        """
        Normzalizes the format of `course`,
        and sends it to the DA.

        Args:
            course: A course timetable.
            year: The year in which the timetable belongs.
            term: The term in which the timetable belongs.

        Returns:
            The response from the DA.
        """
        course = normalize_course(course, year, term)
        try:
            response = requests.put(
                self.config.timetables.endpoint,
                headers=self.config.timetables.headers,
                data=json.dumps(course),
            )
            if not(200 <= response.status_code < 300):
                raise Exception("Failed to send update to DA: {}".format(
                    response.status_code
                ))
        except Exception as e:
            message = "Could not update course: {} {}, {}{}".format(
                term.capitalize(), year,
                course["subject_code"], course["course_code"],
            )
            self.notes.maintainer(message)
            logging.warning(message)
            logging.debug(message, exc_info=True)
        else:
            message = "Updated course: {} {}, {}{}".format(
                term.capitalize(), year,
                course["subject_code"], course["course_code"],
            )
            logging.info(message)
            return response
        return None

    def update_timestamp(self,
        year: int,
        term: str,
        search_list: Optional[Sequence] = None,
    ):
        """Update the DA with the newest timestamp.
        """
        reason = ":".join(str(x).strip() for x in (year, term, "uottawa"))
        try:
            response = requests.put(
                self.config.timestamp.endpoint,
                headers=self.config.timetamp.headers,
                data=json.dumps({"reason": "{}-fullscrape".format(reason)})
            )
            if not(200 <= response.status_code < 300):
                raise Exception("Failed to update timestamp: {}".format(
                    response.status_code
                ))
        except Exception as e:
            message = "Could not update timestamp: {}-fullscrape".format(reason)
            self.notes.maintainer(message)
            logging.warning(message)
            logging.debug(message, exc_info=True)
        else:
            message = "Updated timestamp: {}".format(reason)
            logging.info(message)


    def update_timetables(self,
        year: int,
        term: str,
        search_list: Optional[Sequence] = None,
    ):
        """Update the DA with the newest timetable data.

        Calls the scraper to get the newest timetable data
        for the courses/subjects in `search_list`, 
        and sends the data to the DA.

        See `TimetableUpdater.scrape_timetables` for more information.

        Args:
            year: The year in which to cache timetables in the DA.
            term: The term in which to cache timetables in the DA.
            search_list: The courses/subjects/etc whose timetables
                are to be cached in the DA.  If `None`, cache all courses.

        """
        #@TODO Factor; see line 218 (`scrape_timetables`)
        # See [CS-59]
        is_full_scrape = search_list is None or len(search_list) == 0
        if is_full_scrape:
            self.notes.fullscrape = True
            logging.info("This is a FULLSCRAPE")
            self.update_timestamp(year, term, search_list)
        for course in self.scrape_timetables(year, term, search_list):
            response = self.send_timetable_to_da(course, year, term)
            #@TODO compute diff between course and response
            # if response is not None:
            #   ...
        self.notes.maintainer("Update complete.")
        self.notes.notify_maintainers(only_on_problems=not is_full_scrape)


