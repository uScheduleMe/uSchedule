class TimetableNotifier(_utils.NotifierHandler):

    def __init__(self):
        super().__init__()
        self.fullscrape = False

    def format_data(self) -> dict:
        return {
            "messages": list(self.maintenance_msgs)
                +["---- ISSUES ----"]
                +["{message} -> {exception}".format(**x) for x in self.problems],
            "is_fullscrape": self.fullscrape,
            "subject": "Updating Timetables"
                + "[fullscrape]" if self.fullscrape else "",
            "priority": 1,
        }

    def clear_maintenance_msgs(self):
        """Clear the maintenance messages.

        Automatically called when maintainer notifications are sent.
        """
        super().clear_maintenance_msgs()
        self.fullscrape = False


