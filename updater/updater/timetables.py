class TimetableConfig:
    timestamp: _config.EndpointConfig
    timetables: _config.EndpointConfig
    users: _config.EndpointConfig

    def __init__(self,
        timestamp: _config.EndpointConfig,
        timetables: _config.EndpointConfig,
        users: _config.EndpointConfig,
    ):
        self.timestamp = timestamp
        self.timetables = timetables
        self.users = users

    @classmethod
    def from_args(cls, args):
        return cls(
            _config.make_timestamp_config(args),
            _config.make_timetable_config(args),
            _config.make_users_config(args),
        )

    @classmethod
    def default(cls):
        return cls.from_args(
            _config.EndpointConfig.configure_parser().parse_args([])
        )

    @staticmethod
    def configure_parser(parser):
        return _config.EndpointConfig.configure_parser(parser)


